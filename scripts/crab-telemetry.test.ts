import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseCrabTelemetry,readTsv,receiverSummaries,telemetryBounds,telemetryCsv} from '../app/crab-telemetry-data.ts';
const events=readFileSync(new URL('../research/serc-blue-crab-source/event.txt',import.meta.url),'utf8');
const occurrences=readFileSync(new URL('../research/serc-blue-crab-source/occurrence.txt',import.meta.url),'utf8');
const rows=parseCrabTelemetry(events,occurrences);
assert.equal(rows.length,3346);
assert.equal(new Set(rows.map(r=>r.animal)).size,35);
assert.equal(rows.filter(r=>r.protocol==='tracking tags').length,35);
assert.equal(rows.filter(r=>r.protocol==='acoustic detection').length,3311);
assert.equal(new Set(rows.map(r=>r.id)).size,3346);
assert.ok(rows.every(r=>Number.isFinite(r.time)&&r.latitude>=-90&&r.latitude<=90));
assert.ok(rows.every((r,i)=>i===0||r.time>=rows[i-1].time));
assert.ok(rows.some(r=>r.generalization.includes('subsampled by hour')));
assert.ok(rows.some(r=>r.uncertainty===''));
assert.throws(()=>readTsv('a\tb\n1'));
assert.throws(()=>parseCrabTelemetry(events.replaceAll('38.885512','999'),occurrences));
const csv=telemetryCsv([{...rows[0],station:'=HYPERLINK("test")'}]);
assert.ok(csv.includes("\"'=HYPERLINK(\"\"test\"\")\""));
assert.equal(telemetryCsv(rows).split('\r\n').length,3347);
const bounds=telemetryBounds([rows[0]]);
assert.ok(bounds.west<rows[0].longitude&&bounds.east>rows[0].longitude);
assert.ok(bounds.south<rows[0].latitude&&bounds.north>rows[0].latitude);
const receivers=receiverSummaries(rows);
assert.equal(receivers.reduce((sum,r)=>sum+r.count,0),3311);
assert.ok(receivers.every(r=>r.first.time<=r.last.time));
console.log('17 telemetry checks passed: joins, species, counts, coordinates, ordering, aggregation, missing uncertainty, plot bounds, receivers and export.');
