import assert from 'node:assert/strict';
import {comparableObservations,isChangeEntry,readHistoryImport} from '../app/crab-observation-data.ts';
import {catalogPeriod,crabWorkflows} from '../app/crab-section-workflows.ts';
import {normalizeResearchView,researchViewFromParams,defaultResearchView} from '../app/crab-research-state.ts';
const base={id:'test',date:'2025-01-01',place:'Site A',metric:'Salinity',value:'12',unit:'PSU',note:'Test only',source:'Test fixture',kind:'Observation',method:'Protocol A'};
assert.ok(isChangeEntry(base));
assert.ok(!isChangeEntry({...base,date:'2025-02-30'}));
assert.ok(!isChangeEntry({...base,value:'Infinity'}));
assert.ok(!isChangeEntry({...base,note:null}));
assert.ok(comparableObservations(base,{...base,date:'2025-02-01',value:'14'}));
assert.ok(!comparableObservations(base,{...base,unit:'ppt'}));
assert.ok(!comparableObservations(base,{...base,method:''}));
assert.ok(!comparableObservations(base,{...base,place:'Site B'}));
assert.equal(readHistoryImport({subject:'Callinectes sapidus',section:'nature',records:[base]},'nature').length,1);
assert.throws(()=>readHistoryImport({subject:'Callinectes sapidus',section:'sounds',records:[base]},'nature'));
assert.throws(()=>readHistoryImport({subject:'Callinectes sapidus',section:'nature',records:[{...base,date:'wrong'}]},'nature'));
const record={title:'Fixture',kind:'Test',focus:'Test',description:'',inspect:[],source:'https://example.com/2026',credit:'Study · 1989–2025'};
assert.equal(catalogPeriod(record)?.label,'1989–2025');
assert.equal(catalogPeriod({...record,credit:'Study · 2023'})?.start,2023);
assert.equal(catalogPeriod({...record,credit:'Undated source'}),null);
assert.equal(Object.keys(crabWorkflows).length,13);
assert.equal(catalogPeriod({...record,credit:'Museum accession 1992.11.69'}),null);
assert.equal(catalogPeriod({...record,credit:'Museum accession 1992.11.69 · Published 2023'})?.start,2023);
assert.deepEqual(normalizeResearchView(null),defaultResearchView);
assert.deepEqual(normalizeResearchView({from:'bad',to:'2025-01-01',order:'invalid',mode:'invalid'}),defaultResearchView);
assert.equal(researchViewFromParams(new URLSearchParams('from-year=2000&to-year=2025&display=table')).mode,'table');
assert.equal(researchViewFromParams(new URLSearchParams('from-year=2000&to-year=2025&display=table')).from,'2000');
assert.equal(normalizeResearchView({search:'x'.repeat(700)}).search.length,500);
console.log('22 observation, catalog-date, section-mapping, saved-view and import checks passed.');
